class OrderGenerator:
    def __init__(self, A_items, B_items, C_items, class_weights=(0.1, 0.2, 0.7)):
        self.item_pool = {'A': A_items, 'B': B_items, 'C': C_items}
        self.class_labels = ['A', 'B', 'C']
        self.class_weights = class_weights

    def generate_single_order(self, min_items=10, max_items=50):
        k = random.randint(min_items, max_items)
        # 按指定比例抽取
        item_classes = random.choices(self.class_labels, weights=self.class_weights, k=k)
        order = [random.choice(self.item_pool[cls]) for cls in item_classes]
        return order

    def generate_orders(self, n_orders=1000, min_items=3, max_items=38):
        orders = []
        for _ in range(n_orders):
            orders.append(self.generate_single_order(min_items, max_items))
        return orders

