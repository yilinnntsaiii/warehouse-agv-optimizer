# 工具：build solution for evaluator
def build_solution_for_evaluator(agv_paths, warehouse, depot, order_items):
    coord_small = [depot]
    for item in order_items:
        loc = min(warehouse.item_to_locations[item], key=lambda p: warehouse.dijkstra_distance(depot, p))
        if loc not in coord_small:
            coord_small.append(loc)
    solution = {}
    for agv, batch_routes in agv_paths.items():
        trips = []
        for route in batch_routes:
            local_path = [0]
            for pos in route[1:-1]:
                local_path.append(coord_small.index(pos))
            local_path.append(0)
            trips.append({"path": local_path})
        solution[agv] = trips
    return solution, coord_small

